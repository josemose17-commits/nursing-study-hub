#!/usr/bin/env node
// Builds the Learn → Test → Review engines for Exam 5 and the Final from the Exam 4 one, so every exam that uses it
// works the same way. Each copy gets its own storage keys, globals, topic groups and labels (from its data file:
// D.groupIds, D.groupName). Run after any change to the Exam 4 engine:
//   node tools/build_study_engines.js            (writes e5-* and ef-* engine files)
//   node tools/build_study_engines.js --check    (fails if any copy is out of date)
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
const HEAD = '// Generated by tools/build_study_engines.js from the Exam 4 engine. Do not edit; edit the Exam 4 file and rebuild.\n';
const TARGETS = [
  { key: 'e5', glob: 'E5', name: 'Exam 5', learn: 'Exam 5 Learn.html', file: 'exam5' },
  { key: 'ef', glob: 'EF', name: 'Final', learn: 'Final Learn.html', file: 'final' }
];
function swap(src, pairs, file) {
  pairs.forEach(([from, to, min]) => {
    const n = src.split(from).length - 1;
    if (n < (min == null ? 1 : min)) throw new Error(`${file}: expected "${from}" (found ${n})`);
    src = src.split(from).join(to);
  });
  return src;
}
// A concept may carry its own headed points (Final lessons); otherwise the four standard sections are shown.
const TEACH_OLD = "'<div class=\"ed-chain\"><section><h3>What happens—and why</h3><p>'+md(c.mechanism)+'</p></section><section><h3>What you notice</h3><p>'+md(c.cues)+'</p></section><section><h3>What the nurse does</h3><p>'+md(c.action)+'</p></section><section><h3>How you know it helped</h3><p>'+md(c.evaluate)+'</p></section></div>'";
const TEACH_NEW = "'<div class=\"ed-chain\">'+(c.points?c.points.map(function(p){return '<section><h3>'+esc(p[0])+'</h3><p>'+md(p[1])+'</p></section>';}).join(''):'<section><h3>What happens—and why</h3><p>'+md(c.mechanism)+'</p></section><section><h3>What you notice</h3><p>'+md(c.cues)+'</p></section><section><h3>What the nurse does</h3><p>'+md(c.action)+'</p></section><section><h3>How you know it helped</h3><p>'+md(c.evaluate)+'</p></section>')+'</div>'";

const out = {};
TARGETS.forEach(T => {
  const common = [
    ['E4DiagnosticCore', T.glob + 'DiagnosticCore'], ['E4DiagnosticData', T.glob + 'DiagnosticData', 0], ['E4Review', T.glob + 'Review', 0], ['E4Diagnostic', T.glob + 'Diagnostic', 0],
    ["'e4-", "'" + T.key + '-', 0], ['exam4-diagnostic', T.file + '-diagnostic', 0], ['Exam 4 diagnostic', T.name + ' diagnostic', 0], ["'e4r-", "'" + T.key + 'r-', 0]
  ];
  out[T.key + '-diagnostic-core.js'] = swap(read('e4-diagnostic-core.js'), common, T.key + ' core');
  let review = swap(read('e4-review.js'), common.concat([["require('./e4-diagnostic-core')", "require('./" + T.key + "-diagnostic-core')"]]), T.key + ' review');
  // Exam 4's hand-built connection activities target Exam 4 concepts; the copies review with clinical cases instead.
  review = review.replace(/\n  \/\/ These connections use the already-authored assigned-scope explanations\.[\s\S]*?\n(  function plan)/, '\n$1');
  if (/\n  match\(|\n  order\(/.test(review) || !/\n  function plan\(/.test(review)) throw new Error('could not remove the Exam 4 review activities cleanly');
  out[T.key + '-review.js'] = review;
  out[T.key + '-diagnostic.js'] = swap(read('e4-diagnostic.js'), common.concat([
    [TEACH_OLD, TEACH_NEW],
    ["Chapter '+ch+'</label>'", "'+esc(D.groupName(ch))+'</label>'"],
    ["Chapter '+ch+(ch==='9'?' · Peplau and communication':'')", "'+esc(D.groupName(ch))"],
    ["Chapter '+c.chapter", "'+esc(D.groupName(c.chapter))"],
    ["Chapter '+q.chapter", "'+esc(D.groupName(q.chapter))"],
    ["['3','6','9','34']", 'D.groupIds'],
    ['<legend>Chapters</legend>', '<legend>Topics</legend>'],
    ['Exam 4 Learn.html', T.learn],
    ['Chapters, history and saved work', 'Topics, history and saved work', 0],
    ['selected chapters', 'selected topics', 0],
    ['Choose chapters', 'Choose topics', 0],
    ["(prefs.chapters.length===4?'all four chapters':'Chapter'+(prefs.chapters.length>1?'s ':' ')+prefs.chapters.join(', '))", "(prefs.chapters.length===D.groupIds.length?'all topics':prefs.chapters.length+' of '+D.groupIds.length+' topics')"],
    ["' across all four'", "' across all topics'"],
    ['Chapter detail · ', 'Notes detail · ']
  ]), T.key + ' controller');
});
for (const [f, body] of Object.entries(out)) if (/'e4-|E4Diagnostic|E4Review|'e4r-/.test(body)) throw new Error(f + ' still names Exam 4 storage or globals');

const check = process.argv.includes('--check');
const stale = [];
for (const [f, body] of Object.entries(out)) {
  const text = HEAD + body;
  if (check) { if (!fs.existsSync(path.join(ROOT, f)) || read(f) !== text) stale.push(f); }
  else fs.writeFileSync(path.join(ROOT, f), text);
}
if (check && stale.length) { console.error('Out of date: ' + stale.join(', ') + ' — run node tools/build_study_engines.js'); process.exit(1); }
console.log(check ? 'Study engine copies are current.' : 'Wrote ' + Object.keys(out).join(', '));
