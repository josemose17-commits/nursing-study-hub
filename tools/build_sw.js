#!/usr/bin/env node
// Writes sw.js, the service worker that keeps the whole site working offline. It lists every file the pages use with a
// short content hash, so after a release a phone downloads only the files that changed.
// Run after every release: node tools/build_sw.js      Check it is current: node tools/build_sw.js --check
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
const DIRS = ['data', 'img', '_ds', 'notes', 'icons'];          // folders the pages load from
const SKIP = /(^|\/)(\.|__pycache__|node_modules)|\.(md|py)$/i;   // never cached
const CDN = [ // libraries the older (.dc) pages load from unpkg; cached so those pages also work offline
  'https://unpkg.com/react@18.3.1/umd/react.production.min.js',
  'https://unpkg.com/react-dom@18.3.1/umd/react-dom.production.min.js',
  'https://unpkg.com/@babel/standalone@7.29.0/babel.min.js'
];

function walk(dir, out) {
  if (!fs.existsSync(path.join(ROOT, dir))) return out;
  fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true }).forEach(e => {
    const rel = dir + '/' + e.name;
    if (SKIP.test(rel)) return;
    if (e.isDirectory()) walk(rel, out); else out.push(rel);
  });
  return out;
}
function files() {
  const top = fs.readdirSync(ROOT, { withFileTypes: true })
    .filter(e => e.isFile() && /\.(html|js|css|webmanifest)$/.test(e.name) && e.name !== 'sw.js')
    .map(e => e.name);
  const list = top.concat(...DIRS.map(d => walk(d, []))).sort();
  const map = {};
  list.forEach(f => { map[f] = crypto.createHash('sha1').update(fs.readFileSync(path.join(ROOT, f))).digest('hex').slice(0, 10); });
  return map;
}

function source(map) {
  const version = crypto.createHash('sha1').update(JSON.stringify(map) + CDN.join()).digest('hex').slice(0, 10);
  return `// Generated by tools/build_sw.js: do not edit by hand. Run node tools/build_sw.js after every release.
// Keeps the study hub working offline: every page, script, data file and image is saved on the device the first time
// the site opens. Online, pages still come from the network (so updates show up right away); offline, or when the
// network takes more than a few seconds, the saved copy is used instead.
var VERSION = '${version}';
var FILES = ${JSON.stringify(map, null, 0).replace(/","/g, '",\n"')};
var CDN = ${JSON.stringify(CDN)};
var FILE_CACHE = 'hub-files', CDN_CACHE = 'hub-cdn', WAIT = 4000;
var SCOPE = new URL(self.registration.scope);

function enc(p) { return p.split('/').map(encodeURIComponent).join('/'); }
function keyFor(p) { return new URL(enc(p) + '?sw=' + FILES[p], SCOPE).href; }
function tell(msg) { return self.clients.matchAll({ includeUncontrolled: true }).then(function (cs) { cs.forEach(function (c) { c.postMessage(msg); }); }); }

// Download every file not saved yet (a few at a time). Files already saved with the same hash are skipped, so an
// interrupted download picks up where it stopped and a release only fetches what changed.
function saveAll() {
  return caches.open(FILE_CACHE).then(function (cache) {
    return cache.keys().then(function (reqs) {
      var have = {}; reqs.forEach(function (r) { have[r.url] = 1; });
      var todo = Object.keys(FILES).filter(function (p) { return !have[keyFor(p)]; }), missed = 0;
      function next() {
        var p = todo.shift(); if (!p) return Promise.resolve();
        return fetch(keyFor(p), { cache: 'no-cache' }).then(function (res) {
          if (res.ok) return cache.put(keyFor(p), res); missed++;
        }).catch(function () { missed++; }).then(next);
      }
      var cdn = caches.open(CDN_CACHE).then(function (c) {
        return Promise.all(CDN.map(function (u) {
          return c.match(u).then(function (hit) { return hit || fetch(u, { mode: 'cors' }).then(function (res) { if (res.ok) return c.put(u, res); }).catch(function () {}); }); // retried at the next release; not fatal
        }));
      });
      return Promise.all([next(), next(), next(), next(), next(), next(), cdn]).then(function () { return missed; });
    });
  });
}
function prune() { // remove files from older releases
  return caches.open(FILE_CACHE).then(function (cache) {
    var keep = {}; Object.keys(FILES).forEach(function (p) { keep[keyFor(p)] = 1; });
    return cache.keys().then(function (reqs) { return Promise.all(reqs.filter(function (r) { return !keep[r.url]; }).map(function (r) { return cache.delete(r); })); });
  });
}

self.addEventListener('install', function (e) {
  e.waitUntil(saveAll().then(function (missed) {
    if (missed) throw new Error(missed + ' file(s) could not be saved'); // try again on the next visit
    return self.skipWaiting();
  }));
});
self.addEventListener('activate', function (e) {
  e.waitUntil(prune().then(function () { return self.clients.claim(); }).then(function () { return tell({ type: 'offline-ready', version: VERSION }); }));
});

function saved(p) { return FILES[p] ? caches.match(keyFor(p), { cacheName: FILE_CACHE }) : Promise.resolve(); }
// Network first; the saved copy when offline, on an error, or when the network is slower than WAIT.
function networkFirst(req, p) {
  return new Promise(function (resolve) {
    var done = false;
    function fallback(res) {
      return saved(p).then(function (hit) {
        if (hit) return hit;
        if (res) return res;
        if (req.mode === 'navigate') return saved('index.html').then(function (home) { return home || offlinePage(); });
        return Response.error();
      });
    }
    var timer = setTimeout(function () { saved(p).then(function (hit) { if (hit && !done) { done = true; resolve(hit); } }); }, WAIT);
    fetch(req).then(function (res) {
      if (done) return; done = true; clearTimeout(timer);
      resolve(res.ok || res.status === 304 || !FILES[p] ? res : fallback(res));
    }).catch(function () {
      if (done) return; done = true; clearTimeout(timer); resolve(fallback(null));
    });
  });
}
function offlinePage() {
  return new Response('<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Offline</title><body style="font:16px system-ui;padding:24px;background:#03140c;color:#eee"><h1>You are offline</h1><p>This page has not been saved on this device yet. <a style="color:#f5c400" href="./">Open the home page</a>.</p>', { headers: { 'Content-Type': 'text/html; charset=utf-8' } });
}
function cacheFirst(req) {
  return caches.open(CDN_CACHE).then(function (c) {
    return c.match(req).then(function (hit) {
      return hit || fetch(req).then(function (res) { if (res.ok || res.type === 'opaque') c.put(req, res.clone()); return res; });
    });
  });
}

self.addEventListener('fetch', function (e) {
  var req = e.request; if (req.method !== 'GET') return;
  var url = new URL(req.url);
  if (url.origin !== SCOPE.origin) {
    if (/^(unpkg\\.com|fonts\\.googleapis\\.com|fonts\\.gstatic\\.com)$/.test(url.hostname)) e.respondWith(cacheFirst(req));
    return;
  }
  if (url.pathname.indexOf(SCOPE.pathname) !== 0) return;
  var p; try { p = decodeURIComponent(url.pathname.slice(SCOPE.pathname.length)); } catch (_) { return; }
  if (p === '' || /\\/$/.test(p)) p += 'index.html';
  if (p === 'version.json' || p === 'sw.js') return; // always from the network
  e.respondWith(networkFirst(req, p));
});
`;
}

const out = source(files()), target = path.join(ROOT, 'sw.js');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== out) { console.error('sw.js is out of date: run node tools/build_sw.js'); process.exit(1); }
  console.log('sw.js is current.');
} else {
  fs.writeFileSync(target, out);
  console.log(`sw.js written: ${Object.keys(files()).length} files saved for offline use.`);
}
