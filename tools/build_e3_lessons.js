const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const c = vm.createContext({ window: {} });
for (const ch of ['45', '46', '47', '53', '55', '56']) vm.runInContext(read('data/e3/q/' + ch + '.js'), c);
vm.runInContext(read('data/e3/q/more.js'), c);
const lessons = require('../data/e3/lessons-src.js').map(l => {
  const questions = l.refs.map(ref => {
    if (typeof ref !== 'string') return ref;
    const [ch, kind, index] = ref.split('|');
    const q = kind === 'trad' ? c.window.RECALL_EXTRA[ch].nclex[+index] : c.window.NGN_EXTRA[ch][+index];
    if (!q || !q.o || !q.a || !q.r || (q.f && !['mcq', 'sata', 'exhibit', 'selectn'].includes(q.f))) throw Error('Unsupported lesson question: ' + ref);
    return { id: ref, q: q.q, o: q.o, a: q.a, r: q.r, ex: q.ex || [], phys: q.phys || '' };
  });
  const { refs, ...content } = l;
  return { ...content, questions };
});
const data = { weights: {45:5, 46:10, 47:10, 53:5, 55:10, 56:20}, lessons };
fs.writeFileSync(path.join(root, 'data/e3/lessons.js'), '// Generated by tools/build_e3_lessons.js. Edit lessons-src.js.\nwindow.EXAM3_LESSONS = ' + JSON.stringify(data, null, 2) + ';\n');
console.log('Built ' + lessons.length + ' guided Exam 3 lessons.');
