#!/usr/bin/env node
// Builds the Exam 5 Learn → Test → Review engine from the Exam 4 one, so both exams work the same way.
// The copies get their own storage keys (e5-*), globals (E5Diagnostic…), topic groups and labels from
// data/e5-diagnostic.js (D.groupIds, D.groupName). Run after any change to the Exam 4 engine:
//   node tools/build_e5_study.js            (writes e5-diagnostic-core.js, e5-review.js, e5-diagnostic.js)
//   node tools/build_e5_study.js --check    (fails if the copies are out of date)
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
const HEAD = '// Generated by tools/build_e5_study.js from the Exam 4 engine. Do not edit; edit the Exam 4 file and rebuild.\n';

function swap(src, pairs, file) {
  pairs.forEach(([from, to, min]) => {
    const n = src.split(from).length - 1;
    if (n < (min == null ? 1 : min)) throw new Error(`${file}: expected "${from}" (found ${n})`);
    src = src.split(from).join(to);
  });
  return src;
}
const common = [
  ['E4DiagnosticCore', 'E5DiagnosticCore'], ['E4DiagnosticData', 'E5DiagnosticData', 0], ['E4Review', 'E5Review', 0], ['E4Diagnostic', 'E5Diagnostic', 0],
  ["'e4-", "'e5-", 0], ['exam4-diagnostic', 'exam5-diagnostic', 0], ['Exam 4 diagnostic', 'Exam 5 diagnostic', 0], ["'e4r-", "'e5r-", 0]
];
const out = {
  'e5-diagnostic-core.js': swap(read('e4-diagnostic-core.js'), common, 'core'),
  'e5-review.js': swap(read('e4-review.js'), common.concat([
    // Exam 4's hand-built connection activities target Exam 4 concepts; Exam 5 review uses clinical cases instead.
    ["require('./e4-diagnostic-core')", "require('./e5-diagnostic-core')"]
  ]), 'review'),
  'e5-diagnostic.js': swap(read('e4-diagnostic.js'), common.concat([
    ["Chapter '+ch+'</label>'", "'+esc(D.groupName(ch))+'</label>'"],
    ["Chapter '+ch+(ch==='9'?' · Peplau and communication':'')", "'+esc(D.groupName(ch))"],
    ["Chapter '+c.chapter", "'+esc(D.groupName(c.chapter))"],
    ["Chapter '+q.chapter", "'+esc(D.groupName(q.chapter))"],
    ["['3','6','9','34']", 'D.groupIds'],
    ['<legend>Chapters</legend>', '<legend>Topics</legend>'],
    ['Exam 4 Learn.html', 'Exam 5 Learn.html'],
    ['Chapters, history and saved work', 'Topics, history and saved work', 0],
    ['selected chapters', 'selected topics', 0],
    ['Choose chapters', 'Choose topics', 0],
    ["(prefs.chapters.length===4?'all four chapters':'Chapter'+(prefs.chapters.length>1?'s ':' ')+prefs.chapters.join(', '))", "(prefs.chapters.length===D.groupIds.length?'all topics':prefs.chapters.map(D.groupName).join(', '))"],
    ["' across all four'", "' across all topics'"],
    ['Chapter detail · ', 'Notes detail · ']
  ]), 'controller')
};
// Exam 4 review activities would never match Exam 5 concepts; drop them from the copy so the review queue
// only offers Exam 5 clinical cases.
out['e5-review.js'] = out['e5-review.js'].replace(/\n  \/\/ These connections use the already-authored assigned-scope explanations\.[\s\S]*?\n(  function plan)/, '\n$1');
if (/\n  match\(|\n  order\(/.test(out['e5-review.js']) || !/\n  function plan\(/.test(out['e5-review.js'])) throw new Error('could not remove the Exam 4 review activities cleanly');

for (const [f, body] of Object.entries(out)) if (/'e4-|E4Diagnostic|E4Review|'e4r-/.test(body)) throw new Error(f + ' still names Exam 4 storage or globals');

const check = process.argv.includes('--check');
let stale = [];
for (const [f, body] of Object.entries(out)) {
  const text = HEAD + body;
  if (check) { if (!fs.existsSync(path.join(ROOT, f)) || read(f) !== text) stale.push(f); }
  else fs.writeFileSync(path.join(ROOT, f), text);
}
if (check && stale.length) { console.error('Out of date: ' + stale.join(', ') + ' — run node tools/build_e5_study.js'); process.exit(1); }
console.log(check ? 'Exam 5 engine copies are current.' : 'Wrote ' + Object.keys(out).join(', '));
