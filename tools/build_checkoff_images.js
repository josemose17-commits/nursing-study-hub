#!/usr/bin/env node
// Builds data/checkoff-images.js from the step pictures in img/checkoffs/.
// Pictures were drawn (Gemini) for each station's base steps (data/nrs114-skills.js) and checked against the
// step text. The practice screens use the expanded checkpoints (data/nrs114-checkoff-details.js), so each
// picture lists the checkpoint keys it illustrates. Add a picture: save it as img/checkoffs/<station>-NN.webp
// (720×720 WebP), make sure its row below is right, and run: node tools/build_checkoff_images.js
const fs = require('node:fs'), path = require('node:path');
const ROOT = path.join(__dirname, '..');

// station → base step number → [title, checkpoint keys shown, description of the picture]
const MAP = {
  ivpush: {
    1: ['Verify the order', ['order', 'assess-drug'], 'The nurse compares the printed order with the MAR on the computer.'],
    2: ['Find the administration instructions', ['reference', 'explain-timing'], 'The nurse reads the drug reference, with a clock nearby for the push rate.'],
    3: ['Prepare and label', ['calculate', 'label'], 'In the medication room the nurse draws up the dose; a labeled syringe and saline flushes lie ready.'],
    4: ['Identify and explain', ['identify', 'allergy', 'report'], 'At the bedside the nurse scans the wristband and talks with the patient.'],
    5: ['Trace and assess the access', ['hands', 'trace'], 'Gloved, the nurse traces the extension tubing to the forearm site under a clear dressing.'],
    6: ['Disinfect and let dry', ['scrub'], 'A gloved hand scrubs the needleless connector with an alcohol pad, timed, then lets it dry.'],
    7: ['Check patency gently', ['flush-ready', 'patency'], 'A saline flush on the connector is pushed gently while the nurse watches the site.'],
    8: ['Administer at the verified rate', ['connect-drug', 'time-drug'], 'The nurse pushes the medication slowly, timing it with a watch and watching the patient.'],
    9: ['Deliver the medication left in the line', ['connect-flush', 'clear-dose'], 'A second saline flush clears the medication left in the tubing at the same slow rate.'],
    10: ['Reassess and document', ['dispose', 'record'], 'Sharps disposed and hands cleaned, the nurse checks on the patient and documents.'],
  },
  ivpb: {
    1: ['Verify the medication', ['order'], 'The nurse compares the small medication bag’s label with the MAR on the computer.'],
    2: ['Check the whole fluid path', ['compatibility'], 'Holding the medication bag beside the running primary bag, the nurse checks a compatibility chart.'],
    3: ['Identify and explain', ['identify'], 'The nurse scans the wristband and explains the medication while the IV site is visible.'],
    4: ['Choose the correct setup', ['setup'], 'The nurse traces the primary tubing from the bag through the pump and points to the port above the pump.'],
    5: ['Prime without introducing air', ['prime'], 'Gloved, the nurse spikes the secondary bag and fills the drip chamber and tubing without air.'],
    6: ['Disinfect and connect', ['connect'], 'A gloved hand scrubs the upper port with an alcohol pad, timed, before the secondary line is connected.'],
    7: ['Arrange bags and clamps for this device', ['height'], 'The secondary bag hangs higher than the primary bag, which is lowered on the extension hook, and the clamps are set.'],
    8: ['Program and verify', ['program'], 'The nurse programs the pump while a second nurse double-checks.'],
    9: ['Confirm actual delivery', ['observe'], 'With the infusion started, the nurse checks the IV site and the patient.'],
    10: ['Complete the dose and reassess', ['complete'], 'The secondary bag is empty, the primary infusion is running again, and the nurse documents.'],
  },
};

const dir = path.join(ROOT, 'img/checkoffs'), out = {};
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => /^[a-z-]+-\d\d\.webp$/.test(f)).sort() : [];
for (const f of files) {
  const [, station, nn] = /^([a-z-]+)-(\d\d)\.webp$/.exec(f), n = +nn, row = MAP[station] && MAP[station][n];
  if (!row) throw Error('No mapping for ' + f + ' — add it to MAP in tools/build_checkoff_images.js');
  (out[station] = out[station] || []).push({ n, title: row[0], keys: row[1], alt: row[2], src: 'img/checkoffs/' + f });
}
const text = '// Generated by tools/build_checkoff_images.js from img/checkoffs/. Do not edit by hand.\n' +
  '// Step pictures for the check-off stations: each lists the practice checkpoints (detail keys) it illustrates.\n' +
  'window.CHECKOFF_IMAGES = ' + JSON.stringify(out, null, 1) + ';\n';
if (process.argv.includes('--check')) {
  const now = fs.existsSync(path.join(ROOT, 'data/checkoff-images.js')) ? fs.readFileSync(path.join(ROOT, 'data/checkoff-images.js'), 'utf8') : '';
  if (now !== text) { console.error('data/checkoff-images.js is out of date: run node tools/build_checkoff_images.js'); process.exit(1); }
  console.log('Check-off pictures are current.');
} else {
  fs.writeFileSync(path.join(ROOT, 'data/checkoff-images.js'), text);
  console.log('data/checkoff-images.js: ' + Object.entries(out).map(([s, l]) => s + ' ' + l.length).join(', '));
}
